// ParseDirectoryCmd parses every deck file in a directory into one draft, one
// player per file name.
var ParseDirectoryCmd = &cobra.Command{
	Use:   "parse-dir",
	Short: "Parse a directory of deck files",
	Run: func(cmd *cobra.Command, args []string) {
		// An existing draft supplies the date and event; a new one needs --date.
		if draftID != 0 {
			draft, err := drafts.Find(filepath.Join("data", cubeFlag), draftID)
			if err != nil {
				logrus.WithError(err).Fatalf("Failed to find draft %d", draftID)
			}
			date = draft.Date
			eventCode = draft.EventCode
		}
		if date == "" {
			logrus.Fatal("Must specify --draft or a --date for a new draft.")
		}

		if err := parseDeckDir(deckInputDir, fileType, date); err != nil {
			logrus.WithError(err).Fatal("Failed to parse the deck directory")
		}
	},
}

var (
	anon  bool
	force bool
)

func init() {
	flags := ParseDirectoryCmd.Flags()
	addDraftFlags(flags)
	flag.StringVarP(flags, &deckInputDir, "deck-dir", "d", "DIR", "", "Directory containing deck files to parse.")
	flag.StringVarP(flags, &fileType, "filetype", "f", "TYPE", ".csv", "File type to look for in the deck-dir.")
	flag.StringVarP(flags, &prefix, "prefix", "p", "PREFIX", "", "Prefix to match in the deck file names. Stripped before parsing.")
	flag.BoolVarP(flags, &anon, "anonymous", "a", "", false, "If set, every deck is an anonymous seat with no player.")
	flag.BoolVarP(flags, &force, "force", "", "", false, "If set, force writing of files even if errors are encountered.")
	flags.StringVar(&cubeFlag, "cube", "", "cube id (required)")
	flag.MarkRequired(ParseDirectoryCmd, "cube")
}

// work represents a piece of parsing work to be done: one player's files,
// keyed by the player name or nickname derived from the file name.
type work struct {
	player string
	paths  []string
}

// determinePlayer derives a player name from a deck file name, mapping known
// nicknames to the name in the player list.
func determinePlayer(filename string) string {
	nicknames := map[string]string{
		"jumms":      "james",
		"maserstorm": "dom",
		"phinsup":    "cara",

		"pawl noerros": "paul norris",
		"pawl nawwwis": "paul norris",

		"grrg": "greg",

		"jenjen": "jen",
		"jenno":  "jen",

		"pyrolol": "mattd",
	}
	trimmed := strings.ToLower(strings.TrimPrefix(strings.Split(filename, ".")[0], prefix))

	// Drop any "_suffix" after the player's name.
	trimmed = strings.Split(trimmed, "_")[0]
	if name, ok := nicknames[trimmed]; ok {
		return name
	}
	return trimmed
}

// skipFiles are the file name fragments that mark files to skip when parsing a
// directory. cubecobra.txt is generated by this tool.
var skipFiles = []string{
	"cubecobra.txt",
}

// generateWork groups the deck files in deckDir that end in fileType (and start
// with --prefix, if set) by the player their names give, so a player's mainboard
// and sideboard files are parsed together.
func generateWork(deckDir, fileType string) (map[string]work, error) {
	// Mapping of player name to work item. This allows us to group multiple files
	// for the same player if needed - e.g., a main deck and a sideboard.
	workMap := map[string]work{}

	// Load files from CSV dir.
	fileNames, err := os.ReadDir(deckDir)
	if err != nil {
		return nil, err
	}
	for _, f := range fileNames {
		// Skip some well-known files that we never want to process.
		skip := false
		for _, s := range skipFiles {
			if strings.Contains(f.Name(), s) {
				skip = true
				break
			}
		}
		if skip {
			continue
		}

		if prefix != "" && !strings.HasPrefix(f.Name(), prefix) {
			// Skip files that don't match the prefix, if specified.
			continue
		}
		if strings.HasSuffix(f.Name(), fileType) {
			// Add the file, using the file name as the player name (minus the filetype)
			path := fmt.Sprintf("%s/%s", deckDir, f.Name())

			player := determinePlayer(f.Name())

			// Check if we already have a work item for this player.
			if w, ok := workMap[player]; ok {
				// Append the path to the existing work item.
				w.paths = append(w.paths, path)
				workMap[player] = w
				continue
			}

			workMap[player] = work{
				player: player,
				paths:  []string{path},
			}
		}
	}

	return workMap, nil
}

// checkAnonymousRerun refuses to write anonymous decks into a draft that
// already has some unless --force is set. Seats have no key to match an
// existing deck by, so re-running an anonymous parse would duplicate them.
func checkAnonymousRerun(draft drafts.Draft) error {
	if force {
		return nil
	}
	decks, err := draft.Decks()
	if err != nil {
		return err
	}
	for _, d := range decks {
		if d.PlayerID == 0 {
			return fmt.Errorf("draft %d already has anonymous decks, which a re-run would duplicate; pass --force to add more", draft.ID)
		}
	}
	return nil
}

// parseDeckDir parses every deck in deckDir and, if they all parse and the
// draft is consistent with the cube, writes them into the --draft draft or a
// new one. A new draft is only created once there is something to write.
func parseDeckDir(deckDir, fileType, date string) error {
	logc := logrus.WithFields(logrus.Fields{
		"directory": deckDir,
		"filetype":  fileType,
	})

	// Load work items from the directory.
	workMap, err := generateWork(deckDir, fileType)
	if err != nil {
		return fmt.Errorf("generate work from deck directory: %w", err)
	}

	// If no work to do, exit early.
	if len(workMap) == 0 {
		logc.Info("No files to process.")
		return nil
	}

	logc.WithField("numPlayers", len(workMap)).Info("Processing deck files.")

	// Every card in the deck files, to check against the cube.
	var seenInDraft []types.CountedCard

	var errs []error
	var decks []*types.Deck
	for _, item := range workMap {
		playerID := 0
		if !anon {
			if playerID, err = ResolvePlayer(item.player); err != nil {
				logc.WithError(err).Error("Unknown player.")
				errs = append(errs, err)
				continue
			}
		}
		deck, err := parseDeck(item.paths, playerID, labels, date, 0)
		if err != nil {
			logc.WithError(err).Error("Failed to parse deck file.")
			errs = append(errs, err)
			continue
		}
		decks = append(decks, deck)

		for _, c := range deck.AllCards() {
			seenInDraft = append(seenInDraft, types.CountedCard{Name: c.Name, Count: 1})
		}
	}

	// Any error stops the run before any file is written.
	if len(errs) > 0 {
		return fmt.Errorf("%d decks failed to parse, not writing output files: %w", len(errs), errors.Join(errs...))
	}

	// A cube that won't load fails even with --force, which can only skip a
	// check that ran.
	cube, err := liveCube(cubeFlag)
	if err != nil {
		return fmt.Errorf("load cube %s: %w", cubeFlag, err)
	}
	if err = checkDraftConsistency(logc, cube, seenInDraft); err != nil {
		if !force {
			return fmt.Errorf("draft consistency check failed, not writing output files: %w", err)
		}
		logc.WithError(err).Warn("Draft consistency check failed, but continuing due to --force flag.")
	}

	draft, created, err := resolveDraft(cubeFlag)
	if err != nil {
		return fmt.Errorf("find or create the draft: %w", err)
	}
	return discardOnError(draft, created, writeDraftDecks(draft, decks))
}

// writeDraftDecks writes parsed decks and the cube snapshot into the draft,
// refusing an anonymous re-run that would duplicate its seats.
func writeDraftDecks(draft drafts.Draft, decks []*types.Deck) error {
	if anon {
		if err := checkAnonymousRerun(draft); err != nil {
			return fmt.Errorf("not writing anonymous decks: %w", err)
		}
	}
	if err := writeCubeSnapshot(cubeFlag, draft); err != nil {
		return fmt.Errorf("write cube snapshot: %w", err)
	}
	for _, d := range decks {
		if err := writeDeck(d, draft); err != nil {
			return fmt.Errorf("write deck for player %d: %w", d.PlayerID, err)
		}
	}
	return nil
}

// writeCubeSnapshot saves the live cube list from Cube Cobra with the draft,
// for historical tracking and comparisons. A draft that already has a snapshot
// keeps it.
func writeCubeSnapshot(cube string, draft drafts.Draft) error {
	if draft.HasSnapshot() {
		return nil
	}
	c, err := liveCube(cube)
	if err != nil {
		return err
	}
	return draft.SaveSnapshot(c)
}

// checkDraftConsistency compares the draft's cards with the cube and logs each
// discrepancy. Missing cards only warn; extra copies and cards the cube doesn't
// have fail the check.
func checkDraftConsistency(logc *logrus.Entry, cube *types.Cube, seen []types.CountedCard) error {
	check := cube.CheckDraft(seen)
	logc.WithFields(logrus.Fields{"cube": check.CubeTotal, "seen": check.SeenTotal()}).Info("Checked draft against the cube.")
	for _, discrepancy := range check.Discrepancies {
		entry := logc.WithFields(logrus.Fields{"name": discrepancy.CardName, "seen": discrepancy.Seen, "cube": discrepancy.Cube})
		switch discrepancy.Kind {
		case types.DiscrepancyMissing:
			entry.Warn("Cube card missing from the deck files.")
		case types.DiscrepancyOver:
			entry.Error("More copies in the deck files than the cube has.")
		case types.DiscrepancyUnknown:
			entry.Error("Card in the deck files isn't in the cube.")
		default:
			entry.Warnf("Unexpected discrepancy kind %v.", discrepancy.Kind)
		}
	}
	if numConflicts := check.Conflicts(); numConflicts > 0 {
		return fmt.Errorf("%d cards don't match the cube", numConflicts)
	}
	return nil
}
